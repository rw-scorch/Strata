import { readFileSync } from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const vars = Object.fromEntries(readFileSync('.dev.vars', 'utf8').split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]));
const ADMIN = vars.ADMIN_KEY, WH = vars.STRIPE_WEBHOOK_SECRET;
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const owner = { ownerId: `own-v50-${tag}`, ownerSecret: 'owner-secret-v50-0000' };
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'Realm Fifty', seed: 50, mode: 'survival', difficulty: 'peaceful', ...owner, ownerName: 'Alpha' }) })).json();
const code = room.code;
const info = async () => (await fetch(`${base}/api/rooms/${code}`)).json();
const admin = async (body) => (await fetch(`${base}/api/admin/rooms/${code}`, { method: 'POST', headers: { 'x-admin-key': ADMIN }, body: JSON.stringify(body) })).json();
const join = (id, secret, name) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${code}`);
  const c = { ws, msgs: [], closed: false, send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { c.welcome = m; res(c); } };
  ws.onclose = () => { c.closed = true; res(c); };
  ws.onopen = () => c.send({ t: 'hello', v: 41, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const sign = async (payload) => {
  const t = Math.floor(Date.now() / 1000);
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(WH), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  const sig = Buffer.from(await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(`${t}.${payload}`))).toString('hex');
  return `t=${t},v1=${sig}`;
};
const hook = async (evt) => { const p = JSON.stringify(evt); return fetch(`${base}/api/stripe/webhook`, { method: 'POST', headers: { 'stripe-signature': await sign(p) }, body: p }); };

const cfg = await (await fetch(`${base}/api/hosting/config`)).json();
ok('hosting is enabled when the key and price exist', cfg.enabled === true, JSON.stringify(cfg));
let i = await info();
ok('a new world starts on its short trial', i.host?.phase === 'active' && i.host.until - Date.now() < 4 * 864e5 && i.host.until - Date.now() > 2 * 864e5, JSON.stringify(i.host));
const a = await join(owner.ownerId, owner.ownerSecret, 'Alpha');
ok('owner joins during the trial', a.welcome?.t === 'welcome');
await sleep(1500);
ok('owner is warned that free hosting ends soon', a.msgs.some((m) => m.t === 'chat' && /Realm Hosting/.test(m.text)));
a.ws.close();
await sleep(300);
const bad = await (await fetch(`${base}/api/hosting/checkout`, { method: 'POST', body: JSON.stringify({ code, ownerId: owner.ownerId, ownerSecret: 'wrong-secret-0000000' }) })).json();
ok('checkout refuses non-owners', /owner/i.test(bad.error ?? ''), bad.error);
const co = await fetch(`${base}/api/hosting/checkout`, { method: 'POST', body: JSON.stringify({ code, ...owner }) });
const coj = await co.json();
ok('owner checkout reaches Stripe (fake key is rejected there)', co.status === 502 || !!coj.url, `${co.status} ${coj.error ?? coj.url}`);
let h = await admin({ action: 'hosting', addDays: -40 });
i = await info();
ok('lapsed world shows as frozen', i.host?.phase === 'locked', JSON.stringify(i.host));
const g = await join(`guest-v50-${tag}`, `guest-secret-v50-${tag}`, 'Guest');
ok('frozen world refuses joins with a renew notice', g.welcome?.code === 'unpaid' && /renew/.test(g.welcome.msg), JSON.stringify(g.welcome).slice(0, 160));
const ex = await fetch(`${base}/api/rooms/${code}/export`, { method: 'POST', body: JSON.stringify(owner) });
const exj = await ex.json().catch(() => null);
ok('owner can export a frozen world', ex.ok && exj?.format === 'strata-world' && Object.keys(exj.chunks).length > 0 && exj.meta.name === 'Realm Fifty' && exj.state.player, `${ex.status} chunks=${exj ? Object.keys(exj.chunks).length : 0}`);
const ex2 = await fetch(`${base}/api/rooms/${code}/export`, { method: 'POST', body: JSON.stringify({ ownerId: owner.ownerId, ownerSecret: 'nope-nope-nope-nope' }) });
ok('strangers cannot export', ex2.status === 403);
const until = Date.now() + 30 * 864e5;
const r1 = await hook({ id: `evt_${tag}_1`, type: 'customer.subscription.updated', data: { object: { id: `sub_${tag}`, status: 'active', customer: 'cus_test', metadata: { kind: 'hosting', room: code }, items: { data: [{ current_period_end: Math.floor(until / 1000) }] } } } });
ok('signed hosting webhook is accepted', r1.ok, String(r1.status));
i = await info();
ok('payment unfreezes and renews the world', i.host?.phase === 'active' && i.host.renewing && Math.abs(i.host.until - until) < 2000, JSON.stringify(i.host));
const g2 = await join(`guest-v50-${tag}`, `guest-secret-v50-${tag}`, 'Guest');
ok('players can join again after payment', g2.welcome?.t === 'welcome');
g2.ws.close();
const forged = await fetch(`${base}/api/stripe/webhook`, { method: 'POST', headers: { 'stripe-signature': 't=1,v1=00' }, body: '{}' });
ok('forged webhook is rejected', forged.status === 400);
await hook({ id: `evt_${tag}_2`, type: 'customer.subscription.deleted', data: { object: { id: `sub_${tag}`, status: 'canceled', customer: 'cus_test', metadata: { kind: 'hosting', room: code }, items: { data: [{ current_period_end: Math.floor(until / 1000) }] } } } });
i = await info();
ok('cancelling keeps the paid month but stops renewing', i.host?.phase === 'active' && !i.host.renewing, JSON.stringify(i.host));
h = await admin({ action: 'hosting', comp: true });
ok('admin can host a world free', h.host?.phase === 'comp', JSON.stringify(h.host));
await admin({ action: 'hosting', comp: false });
await hook({ id: `evt_${tag}_3`, type: 'customer.subscription.updated', data: { object: { id: `sub_${tag}`, status: 'canceled', customer: 'cus_test', metadata: { kind: 'hosting', room: code }, items: { data: [{ current_period_end: 1 }] } } } });
const adminEx = await fetch(`${base}/api/admin/rooms/${code}/export`, { method: 'POST', headers: { 'x-admin-key': ADMIN } });
ok('admin export works', adminEx.ok && (await adminEx.json()).format === 'strata-world');
console.log(fails ? `${fails} failed` : 'all passed');
process.exit(fails ? 1 : 0);
