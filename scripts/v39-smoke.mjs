const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V39', seed: 3939, mode: 'creative', difficulty: 'peaceful', ownerId: `own-v39-${tag}`, ownerSecret: 'owner-secret-v39-0000', ownerName: 'Alpha' }) })).json();
const info = await (await fetch(`${base}/api/rooms/${room.code}`)).json();
ok('room lookup reports exists', info.exists === true);
const missing = await fetch(`${base}/api/rooms/ZZZZ9999`);
const mj = await missing.json();
ok('unknown code reports exists:false explicitly', missing.ok && mj.exists === false);
const join = (id, secret, name) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome') { c.you = m.you; res(c); } };
  ws.onopen = () => c.send({ t: 'hello', v: 37, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const a = await join(`own-v39-${tag}`, 'owner-secret-v39-0000', 'Alpha');
const b = await join(`guest-v39-${tag}`, `guest-secret-v39-${tag}`, 'Bravo');
await sleep(1500);
const spos = (c) => c.msgs.filter((m) => m.t === 'spos');
ok('no positions shared by default', !spos(b).some((m) => m.l.length));
a.send({ t: 'share', to: [b.you.id], all: false });
await sleep(2200);
const last = spos(b).at(-1);
ok('sharing sends my position to the chosen player', !!last && last.l.some((r) => r[0] === a.you.id && r[1] === 'Alpha'), JSON.stringify(last));
ok('the sharer does not receive their own position', !spos(a).some((m) => m.l.some((r) => r[0] === a.you.id)));
a.send({ t: 'share', to: [], all: false });
await sleep(2200);
ok('stopping sharing clears it', (spos(b).at(-1)?.l.length ?? 0) === 0);
a.msgs.length = 0;
a.send({ t: 'inv', op: { t: 'swapHand' }, s: 7 });
a.send({ t: 'resync' });
await sleep(600);
const inv = a.msgs.find((m) => m.t === 'inv');
ok('inventory updates carry the last processed move', inv?.q === 7, JSON.stringify(inv?.q));
a.msgs.length = 0;
a.send({ t: 'chat', text: '/eco on' });
await sleep(900);
const cat = [{ id: 'gems', name: 'Gems', icon: 389, items: [{ key: 'lapis_lazuli', id: 389, count: 16, price: 321 }] }];
a.send({ t: 'eco', a: 'shopSet', cat });
await sleep(800);
const pr = a.msgs.filter((m) => m.t === 'eco' && m.k === 'prices').at(-1);
ok('admins can replace the shop catalogue', pr?.cat?.[0]?.id === 'gems' && pr.shop.lapis_lazuli === 321, JSON.stringify(pr?.cat?.[0]));
b.msgs.length = 0;
b.send({ t: 'eco', a: 'shopSet', cat: [] });
await sleep(600);
ok('non-admins cannot edit the shop', b.msgs.some((m) => m.t === 'chat' && /Only operators/.test(m.text)));
a.send({ t: 'eco', a: 'shopSet', reset: true });
await sleep(600);
const pr2 = a.msgs.filter((m) => m.t === 'eco' && m.k === 'prices').at(-1);
ok('reset restores the default shop with lapis and diamond armour', pr2?.cat?.length >= 5 && 'aetherite_boots' in pr2.shop && 'lapis_lazuli' in pr2.shop);
a.ws.close(); b.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
