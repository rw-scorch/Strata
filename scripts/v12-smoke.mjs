const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
const ok = (label, cond, extra = '') => { console.log(cond ? 'PASS' : 'FAIL', label, extra); if (!cond) process.exitCode = 1; };
const tag = Date.now().toString(36);
const created = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V12 Smoke', seed: 912, mode: 'creative', difficulty: 'normal', ownerId: `owner-v12-${tag}`, ownerSecret: 'owner-secret-v12-0000', ownerName: 'Alpha' }) })).json();
const code = created.code;
function client(id, secret, name) {
  const ws = new WebSocket(`${wsBase}/ws/${code}`);
  const c = { ws, msgs: [], welcome: null };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome') c.welcome = m; };
  ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 7, id, secret, name, appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
  c.send = (m) => ws.send(JSON.stringify(m));
  c.chats = () => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
  c.inv = () => c.msgs.filter((m) => m.t === 'inv').at(-1)?.inv;
  return c;
}
const a = client(`owner-v12-${tag}`, 'owner-secret-v12-0000', 'Alpha');
await sleep(800);
const b = client(`guest-v12-${tag}`, 'guest-secret-v12-0000', 'Bravo');
await sleep(1500);
ok('both joined', !!a.welcome && !!b.welcome);
ok('no recipes at start', !a.welcome.recipes);
const pack = { name: 'Smoke Pack', hash: 'ab12', crafting: [{ id: 'smoke:dirt_to_emerald', group: 'basics', result: 295, count: 5, shapeless: [3] }], smelting: [{ input: 3, result: 256, xp: 1 }], remove: ['bread'] };
b.send({ t: 'datapacks', d: [pack] });
await sleep(400);
ok('guest cannot change data packs', b.chats().some((t) => /Only the world owner/.test(t)) && !a.msgs.some((m) => m.t === 'recipes'));
a.send({ t: 'datapacks', d: [pack, { name: 'Bad', crafting: [{ id: 'x', result: 99999, shapeless: [3] }] }] });
await sleep(500);
const rb = b.msgs.find((m) => m.t === 'recipes');
ok('recipes broadcast to guest', rb && rb.d.length === 1 && rb.d[0].crafting[0].result === 295, JSON.stringify(rb?.d.map((d) => d.name)));
ok('change announced', b.chats().some((t) => /changed the data packs/.test(t)));
a.send({ t: 'inv', op: { t: 'creative', id: 3, count: 1 }, s: 1 });
await sleep(200);
a.send({ t: 'inv', op: { t: 'click', s: { c: 'craft', i: 0 }, b: 0 }, s: 3 });
await sleep(300);
a.send({ t: 'inv', op: { t: 'click', s: { c: 'out', i: 0 }, b: 0 }, s: 2 });
await sleep(300);
a.send({ t: 'resync' });
await sleep(400);
const inv = a.inv();
ok('server crafts with data pack recipe', inv?.cursor?.id === 295 && inv.cursor.count === 5, JSON.stringify(inv?.cursor));
const big = { name: 'Huge', hash: 'cc', crafting: Array.from({ length: 900 }, (_, i) => ({ id: `big:r${i}`, group: 'basics', result: 256, count: 1, pattern: ['AB', 'BA'], key: { A: 3, B: [1, 2, 4, 5, 7, 8] } })), smelting: [], remove: [] };
await sleep(4200);
a.send({ t: 'datapacks', d: [big] });
await sleep(800);
const last = b.msgs.filter((m) => m.t === 'recipes').at(-1);
ok('oversized pack is capped', last && last.d[0].crafting.length <= 600, String(last?.d[0]?.crafting.length));
a.ws.close(); b.ws.close();
await sleep(300);
const c = client(`guest-v12-${tag}`, 'guest-secret-v12-0000', 'Bravo');
await sleep(1500);
ok('rejoin welcome has recipes', c.welcome?.recipes?.length === 1);
c.ws.close();
await sleep(200);
process.exit();
