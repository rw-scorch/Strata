const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const r = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'Swap', seed: 2020, mode: 'survival', difficulty: 'normal', ownerId: `owner-v20-${tag}`, ownerSecret: 'owner-secret-v20-0000', ownerName: 'Alpha' }) })).json();
function client(id, secret, name) {
  const ws = new WebSocket(`${wsBase}/ws/${r.code}`);
  const c = { msgs: [], welcome: null };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome') c.welcome = m; };
  ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 17, id, secret, name, appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
  c.send = (m) => ws.send(JSON.stringify(m));
  c.close = () => ws.close();
  c.health = () => { const v = c.msgs.filter((m) => m.t === 'vit').at(-1); return v ? v.h : 20; };
  c.inv = () => c.msgs.filter((m) => m.t === 'inv').at(-1)?.inv;
  return c;
}
const a = client(`owner-v20-${tag}`, 'owner-secret-v20-0000', 'Alpha');
await sleep(1500);
const sp = a.welcome.you;
const b = client(`guest-v20-${tag}`, 'guest-secret-v20-0000', 'Bravo');
await sleep(1500);
a.send({ t: 'chat', text: '/give @s mace' }); await sleep(300);
a.send({ t: 'chat', text: '/give @s aetherite_sword' }); await sleep(300);
const inv = a.inv();
const mi = inv.slots.findIndex((s) => s?.id === 381), si = inv.slots.findIndex((s) => s?.id === 323);
ok('owner has a mace and a sword in the hotbar', mi >= 0 && mi < 9 && si >= 0 && si < 9, `${mi} ${si}`);
a.send({ t: 'inv', op: { t: 'select', i: mi }, s: 1 });
const place = () => { a.send({ t: 'mv', p: [sp.x, sp.y, sp.z, -Math.PI / 2, 0, 1] }); b.send({ t: 'mv', p: [sp.x + 2, sp.y, sp.z, 0, 0, 1] }); };
place(); await sleep(1800);
const h0 = b.health();
a.send({ t: 'inv', op: { t: 'select', i: si }, s: 2 });
a.send({ t: 'pvp', pid: `guest-v20-${tag}` });
await sleep(500);
const lost = h0 - b.health();
ok('same-tick swap: sword hit with the mace attack damage (6)', Math.abs(lost - 6) < 0.6, `lost ${lost}`);
const sw = a.inv().slots[si];
ok('the sword takes the wear', (sw?.dmg ?? 0) === 1, JSON.stringify(sw));
await sleep(1500);
a.send({ t: 'inv', op: { t: 'select', i: mi }, s: 3 });
await sleep(200);
const h1 = b.health();
a.send({ t: 'pvp', pid: `guest-v20-${tag}` });
await sleep(500);
const lost2 = h1 - b.health();
ok('a normal swap resets the cooldown (weak hit)', lost2 > 0 && lost2 < 3, `lost ${lost2}`);
a.close(); b.close();
await sleep(300);
console.log(fails ? `${fails} FAILED` : 'ALL PASS');
process.exit(fails ? 1 : 0);
