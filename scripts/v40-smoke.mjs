const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V40', seed: 40, mode: 'survival', difficulty: 'normal', ownerId: `own-v40-${tag}`, ownerSecret: 'owner-secret-v40-0000', ownerName: 'Alpha' }) })).json();
const join = (id, secret, name, v = 34) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], closed: null, send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { c.you = m.you; c.welcome = m; res(c); } };
  ws.onclose = (e) => { c.closed = e.code; res(c); };
  ws.onopen = () => c.send({ t: 'hello', v, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const chats = (c) => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const old = await join(`old-v40-${tag}`, `old-secret-v40-${tag}`, 'Old', 33);
ok('protocol 33 clients are turned away', old.welcome?.t !== 'welcome', JSON.stringify(old.welcome ?? old.closed));
const a = await join(`own-v40-${tag}`, 'owner-secret-v40-0000', 'Alpha');
ok('owner joins on protocol 34', a.welcome?.t === 'welcome');
a.send({ t: 'chat', text: '/tp 100 64 0 end' });
await sleep(1500);
const tp = a.msgs.filter((m) => m.t === 'tp').at(-1);
ok('/tp ... end lands in the End band', tp && tp.x < -300000, JSON.stringify(tp));
const chunksBefore = a.msgs.filter((m) => m.t === 'chunk').length;
const want = [];
for (let r = 0; r <= 6; r++) for (let i = -r; i <= r; i++) for (let j = -r; j <= r; j++) if (Math.max(Math.abs(i), Math.abs(j)) === r) want.push([Math.floor(tp.x / 16) + i, j]);
for (let k = 0; k < want.length; k += 24) { a.send({ t: 'chunks', want: want.slice(k, k + 24) }); await sleep(300); }
for (let i = 0; i < 16; i++) { a.send({ t: 'mv', p: [tp.x, tp.y, tp.z, 0, 0, 0] }); await sleep(500); }
ok('End chunks stream in', a.msgs.filter((m) => m.t === 'chunk').length > chunksBefore);
const added = a.msgs.filter((m) => m.t === 'ent').flatMap((m) => m.a);
const mobs = added.filter((r) => r[1] === added.find((x) => x[2] === 19)?.[1]);
ok('the Ender Dragon is in the fight', added.some((r) => r[2] === 19), `types ${[...new Set(added.map((r) => r[2]))].join(',')}`);
ok('End crystals stand on the pillars', added.filter((r) => r[2] === 20).length >= 1, `${mobs.length}`);
a.send({ t: 'chat', text: '/tp 0 80 0 overworld' });
await sleep(1500);
const tp2 = a.msgs.filter((m) => m.t === 'tp').at(-1);
ok('/tp ... overworld comes back', tp2 && Math.abs(tp2.x) < 1000, JSON.stringify(tp2));
a.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
