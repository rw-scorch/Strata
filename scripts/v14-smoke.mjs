function client(id, secret, name) {
  const ws = new WebSocket(`${wsBase}/ws/${code}`);
  const c = { ws, msgs: [], welcome: null };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome') c.welcome = m; };
  ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 9, id, secret, name, appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
  c.send = (m) => ws.send(JSON.stringify(m));
  c.say = async (t, wait = 350) => { c.send({ t: 'chat', text: t }); await sleep(wait); };
  c.chats = () => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
  c.last = () => c.chats().at(-1) ?? '';
  c.money = () => c.msgs.filter((m) => m.t === 'eco' && m.k === 'stats').at(-1)?.money;
  c.view = () => c.msgs.filter((m) => m.t === 'eco' && m.k === 'view').at(-1)?.view;
  c.inv = async () => { c.send({ t: 'resync' }); await sleep(300); return c.msgs.filter((m) => m.t === 'inv').at(-1)?.inv; };
  return c;
}
