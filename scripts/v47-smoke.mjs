const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V47', seed: 47, mode: 'survival', difficulty: 'peaceful', ownerId: `own-v47-${tag}`, ownerSecret: 'owner-secret-v47-0000', ownerName: 'Alpha' }) })).json();
const join = (id, secret, name) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { c.you = m.you; c.welcome = m; res(c); } };
  ws.onclose = () => res(c);
  ws.onopen = () => c.send({ t: 'hello', v: 39, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const chats = (c) => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const cru = (c) => c.msgs.filter((m) => m.t === 'cru').map((m) => m.s);
const a = await join(`own-v47-${tag}`, 'owner-secret-v47-0000', 'Alpha');
const g = await join(`guest-v47-${tag}`, `guest-secret-v47-${tag}`, 'Guest');
ok('both join on protocol 39', a.welcome?.t === 'welcome' && g.welcome?.t === 'welcome');
await sleep(4000);
a.send({ t: 'chat', text: '/crucible start r=10 join=60 kit=diamond money=1500 second=0 prize=golden_apple:2,experience_bottle:8,diamond_sword+:1 ring=on time=120' });
await sleep(1500);
ok('owner opens the Crucible with a long command', chats(a).some((t) => /Crucible open/.test(t)), chats(a).slice(-1).join(''));
ok('guest sees the call to arms', chats(g).some((t) => /\/crucible join/.test(t)));
ok('guest gets the event state', cru(g).at(-1)?.ph === 'open');
g.send({ t: 'chat', text: '/crucible join' });
await sleep(400);
a.send({ t: 'chat', text: '/crucible join' });
await sleep(900);
ok('both entered', cru(g).at(-1)?.n === 2, JSON.stringify(cru(g).at(-1)));
const late = await join(`late-v47-${tag}`, `late-secret-v47-${tag}`, 'Late');
await sleep(700);
ok('a late joiner is told about the open event', late.msgs.some((m) => m.t === 'cru' && m.s?.ph === 'open'));
a.send({ t: 'chat', text: '/crucible go' });
await sleep(1200);
ok('fighters are pulled in', g.msgs.some((m) => m.t === 'tp') && cru(g).at(-1)?.ph === 'ready');
ok('guest wears the kit', JSON.stringify(g.msgs.filter((m) => m.t === 'inv').at(-1)?.inv?.armor ?? []).includes('protection'));
await sleep(5600);
ok('the fight starts', cru(g).at(-1)?.ph === 'fight', JSON.stringify(cru(g).at(-1)));
g.send({ t: 'chat', text: '/home' });
g.send({ t: 'chat', text: '/shop' });
await sleep(900);
ok('teleports and the shop are blocked for fighters', chats(g).filter((t) => /inside the Crucible/.test(t)).length >= 2, chats(g).slice(-2).join(' | '));
g.send({ t: 'chat', text: '/crucible leave' });
await sleep(1200);
ok('forfeit names the champion', chats(a).some((t) => /Alpha is Champion of the Crucible/.test(t)), chats(a).slice(-1).join(''));
await sleep(4800);
ok('the event closes', cru(a).at(-1) === null);
a.send({ t: 'chat', text: '/bal' });
await sleep(900);
ok('the champion is paid', chats(a).some((t) => /Balance: \$1(,)?500|\$1\.5K/i.test(t)), chats(a).slice(-1).join(''));
const inv = JSON.stringify(a.msgs.filter((m) => m.t === 'inv').at(-1) ?? {});
ok('the champion gets the prize items', inv.includes(`"id":291`) && inv.includes('sharpness'));
a.ws.close(); g.ws.close(); late.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
