const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const created = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'Piston', seed: 4343, mode: 'creative', difficulty: 'peaceful', maxPlayers: 4, ownerId: 'owner-ember-0001', ownerSecret: 'owner-secret-ember-0000', ownerName: 'Alpha' }) })).json();
const code = created.code;
const ws = new WebSocket(`${wsBase}/ws/${code}`);
const a = { msgs: [], welcome: null, blocks: new Map(), hist: [] };
ws.onmessage = (e) => { const m = JSON.parse(e.data); a.msgs.push(m); if (m.t === 'welcome') a.welcome = m; if (m.t === 'blk') for (const u of m.u) { a.blocks.set(`${u[0]},${u[1]},${u[2]}`, u[3]); a.hist.push(u); } };
ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 12, id: 'owner-ember-0001', secret: 'owner-secret-ember-0000', name: 'Alpha', appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
const send = (m) => ws.send(JSON.stringify(m));
const say = async (t, ms = 950) => { send({ t: 'chat', text: t }); await sleep(ms); };
await sleep(1500);
const sp = a.welcome.you;
const x0 = Math.floor(sp.x) + 4, y0 = Math.min(150, Math.floor(sp.y) + 20), z0 = Math.floor(sp.z);
await say(`/tp ${x0 + 2.5} ${y0 + 1} ${z0 + 2.5}`);
send({ t: 'mv', p: [x0 + 2.5, y0 + 1, z0 + 2.5, 0, 0, 9] });
await say(`/pos1 ${x0 - 1} ${y0} ${z0 - 1}`); await say(`/pos2 ${x0 + 8} ${y0} ${z0 + 3}`); await say('/fill stone', 1200);
const look = async (yaw, pitch = 0) => { send({ t: 'mv', p: [x0 + 2.5, y0 + 1, z0 + 2.5, yaw, pitch, 9] }); await sleep(150); };
const put = async (id, x, z = z0) => { send({ t: 'inv', op: { t: 'creative', id, count: 64, s: { c: 'inv', i: 0 } }, s: Math.floor(Math.random() * 1e6) }); await sleep(150); send({ t: 'use', x, y: y0, z, nx: 0, ny: 1, nz: 0 }); await sleep(250); };
const v = (x, z = z0) => a.blocks.get(`${x},${y0 + 1},${z}`);
await look(Math.PI / 2);
await put(198, x0 + 6);
ok('piston placed facing east', (v(x0 + 6) & 0xff) === 198 && ((v(x0 + 6) >>> 8) & 7) === 1, String(v(x0 + 6)));
await put(4, x0 + 7);
await put(190, x0 + 5);
await sleep(600);
ok('piston extends', ((v(x0 + 6) >>> 8) & 8) === 8, String(v(x0 + 6)));
ok('head appears', (v(x0 + 7) & 0xff) === 200, String(v(x0 + 7)));
ok('block pushed', (v(x0 + 8) & 0xff) === 4, String(v(x0 + 8)));
await look(Math.PI);
await put(197, x0 + 1);
ok('watcher faces south', ((v(x0 + 1) >>> 8) & 7) === 5, String(v(x0 + 1)));
await put(191, x0 + 1, z0 - 1);
a.hist.length = 0;
await put(1, x0 + 1, z0 + 1);
await sleep(600);
ok('watcher pulse lights the lamp', a.hist.some((u) => u[0] === x0 + 1 && u[2] === z0 - 1 && (u[3] & 0xff) === 192));
ok('lamp goes back off', (v(x0 + 1, z0 - 1) & 0xff) === 191, String(v(x0 + 1, z0 - 1)));
ws.close();
await sleep(300);
console.log(fails ? `${fails} FAILED` : 'ALL PASS');
process.exit(fails ? 1 : 0);
