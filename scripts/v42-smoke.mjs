const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V42', seed: 42, mode: 'survival', difficulty: 'normal', ownerId: `own-v42-${tag}`, ownerSecret: 'owner-secret-v42-0000', ownerName: 'Alpha' }) })).json();
const join = (id, secret, name, v = 36) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], closed: null, send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { c.you = m.you; c.welcome = m; res(c); } };
  ws.onclose = (e) => { c.closed = e.code; res(c); };
  ws.onopen = () => c.send({ t: 'hello', v, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const chats = (c) => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const old = await join(`old-v42-${tag}`, `old-secret-v42-${tag}`, 'Old', 35);
ok('protocol 35 clients are turned away', old.welcome?.t !== 'welcome', JSON.stringify(old.welcome ?? old.closed));
const a = await join(`own-v42-${tag}`, 'owner-secret-v42-0000', 'Alpha');
ok('owner joins on protocol 36', a.welcome?.t === 'welcome');
await sleep(1500);
a.send({ t: 'chat', text: '/tp 40 90 40' });
await sleep(700);
ok('/tp starts a 3 second warm-up', chats(a).some((t) => /Teleporting in 3 seconds/.test(t)), JSON.stringify(chats(a).slice(-2)));
ok('nobody moves before the warm-up ends', !a.msgs.some((m) => m.t === 'tp'));
await sleep(3200);
ok('the teleport lands after the warm-up', a.msgs.some((m) => m.t === 'tp' && Math.abs(m.x - 40) < 1), JSON.stringify(a.msgs.filter((m) => m.t === 'tp')));
a.send({ t: 'chat', text: '/give @s cinderite_sword 1' });
await sleep(600);
a.send({ t: 'chat', text: '/enchantmax' });
await sleep(800);
ok('/enchantmax applies a full set', chats(a).some((t) => /Applied .*Sharpness V.*Mending/.test(t)), JSON.stringify(chats(a).slice(-1)));
a.send({ t: 'chat', text: '/give @s item_frame 2' });
a.send({ t: 'chat', text: '/give @s hopper_minecart 1' });
await sleep(800);
const inv = JSON.stringify(a.msgs.filter((m) => m.t === 'inv').at(-1) ?? {});
ok('item frames and hopper minecarts exist on the server', inv.includes('"id":501') && inv.includes('"id":503'));
a.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
