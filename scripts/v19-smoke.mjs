const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const created = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'Rail', seed: 5555, mode: 'creative', difficulty: 'peaceful', maxPlayers: 4, ownerId: 'owner-rail-0000001', ownerSecret: 'owner-secret-rail-000000', ownerName: 'Alpha' }) })).json();
const code = created.code;
const ws = new WebSocket(`${wsBase}/ws/${code}`);
const a = { msgs: [], welcome: null, blocks: new Map(), hist: [] };
ws.onmessage = (e) => { const m = JSON.parse(e.data); a.msgs.push(m); if (m.t === 'welcome') a.welcome = m; if (m.t === 'blk') for (const u of m.u) { a.blocks.set(`${u[0]},${u[1]},${u[2]}`, u[3]); a.hist.push(u); } };
ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 17, id: 'owner-rail-0000001', secret: 'owner-secret-rail-000000', name: 'Alpha', appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
const send = (m) => ws.send(JSON.stringify(m));
const say = async (t, ms = 950) => { send({ t: 'chat', text: t }); await sleep(ms); };
await sleep(1500);
const sp = a.welcome.you;
const x0 = Math.floor(sp.x) + 4, y0 = Math.min(150, Math.floor(sp.y) + 20), z0 = Math.floor(sp.z);
await say(`/tp ${x0 + 2.5} ${y0 + 1} ${z0 + 2.5}`);
send({ t: 'mv', p: [x0 + 2.5, y0 + 1, z0 + 2.5, 0, 0, 9] });
await say(`/pos1 ${x0 - 1} ${y0} ${z0 - 1}`); await say(`/pos2 ${x0 + 8} ${y0} ${z0 + 3}`); await say('/fill stone', 1200);
const look = async (yaw, pitch = 0) => { send({ t: 'mv', p: [x0 + 2.5, y0 + 1, z0 + 2.5, yaw, pitch, 9] }); await sleep(150); };
const put = async (id, x, z = z0, h) => { send({ t: 'inv', op: { t: 'creative', id, count: 64, s: { c: 'inv', i: 0 } }, s: Math.floor(Math.random() * 1e6) }); await sleep(150); send({ t: 'use', x, y: y0, z, nx: 0, ny: 1, nz: 0, ...(h !== undefined ? { h } : {}) }); await sleep(250); };
const v = (x, z = z0) => a.blocks.get(`${x},${y0 + 1},${z}`);
await look(Math.PI / 2);
for (let i = 0; i < 6; i++) await put(210, x0 + i);
const shapes = [0,1,2,3,4,5].map((i) => (v(x0 + i) >>> 8) & 15);
ok('rails join into a straight east-west line', shapes.every((s) => s === 1), JSON.stringify(shapes));
await put(210, x0 + 5, z0 + 1);
ok('a side rail turns the end into a curve', ((v(x0 + 5) >>> 8) & 15) >= 6, String((v(x0 + 5) >>> 8) & 15));
a.msgs.length = 0;
send({ t: 'inv', op: { t: 'creative', id: 374, count: 1, s: { c: 'inv', i: 0 } }, s: 99 }); await sleep(200);
send({ t: 'use', x: x0 + 2, y: y0 + 1, z: z0, nx: 0, ny: 1, nz: 0 }); await sleep(600);
const carts = a.msgs.filter((m) => m.t === 'ent').flatMap((m) => m.a).filter((r) => r[1] === 4);
ok('placing a minecart makes a cart entity', carts.length > 0, JSON.stringify(carts.slice(0, 1)));
if (carts.length) {
  send({ t: 'ue', id: carts[0][0] }); await sleep(500);
  const r = a.msgs.find((m) => m.t === 'ride');
  ok('using the cart mounts it', !!r && r.id === carts[0][0], JSON.stringify(r ?? null));
  send({ t: 'mv', p: [x0 + 2.5, y0 + 1.4, z0 + 0.5, 0, 0, 2 | 8192] }); await sleep(500);
  ok('crouching gets off', a.msgs.some((m) => m.t === 'ride' && m.id === -1));
}
ws.close();
await sleep(300);
console.log(fails ? `${fails} FAILED` : 'ALL PASS');
process.exit(fails ? 1 : 0);
