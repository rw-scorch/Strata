import { readFileSync } from 'node:fs';
const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const vars = Object.fromEntries(readFileSync('.dev.vars', 'utf8').split('\n').filter((l) => l.includes('=')).map((l) => [l.slice(0, l.indexOf('=')).trim(), l.slice(l.indexOf('=') + 1).trim()]));
const ADMIN = vars.ADMIN_KEY, WH = vars.STRIPE_WEBHOOK_SECRET;
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const post = async (path, body, headers = {}) => { const r = await fetch(base + path, { method: 'POST', headers, body: JSON.stringify(body) }); return { status: r.status, data: await r.json() }; };
const tag = Date.now().toString(36).slice(-6);
const reg = await post('/api/auth/register', { name: `shop_${tag}`, password: 'hunter22' });
ok('account registers', !!reg.data.id, JSON.stringify(reg.data));
const me = { id: reg.data.id, secret: reg.data.secret };
const shop = (op, extra = {}) => post(`/api/shop/${op}`, { ...me, ...extra });

const cfg = await (await fetch(base + '/api/shop/config')).json();
ok('shop is open when Stripe and packs are configured', cfg.enabled === true);
let s = await shop('state');
ok('new wallet is empty with offers and packs', s.data.shards === 0 && s.data.keys === 0 && s.data.offers.wanderer.length === 3 && s.data.packs.length === 2, JSON.stringify(s.data).slice(0, 200));
ok('pack price ids are not sent to the client', !JSON.stringify(s.data.packs).includes('price_'));
ok('bad secret is refused', (await post('/api/shop/state', { id: me.id, secret: 'nope' })).status === 401);
s = await shop('daily');
ok('daily key claims once', s.data.keys === 1 && s.data.canClaim === false);
ok('second daily claim is refused', (await shop('daily')).status === 409);
ok('cannot buy without shards', (await shop('buy', { item: 'c_ember' })).status === 402);
ok('cannot equip what you do not own', (await shop('equip', { kind: 'cape', item: 'c_ember' })).status === 403);
const off = s.data.offers.wanderer;
ok('cannot open a cache with too few keys', (await shop('crate', { crate: 'wanderer', item: off[0], pay: 'keys' })).status === 402);
ok('admin needs the key', (await post('/api/admin/shards', { name: `shop_${tag}`, shards: 5000 })).status === 401);
const adj = await post('/api/admin/shards', { name: `shop_${tag}`, shards: 3000, keys: 5 }, { 'x-admin-key': ADMIN });
ok('admin grants shards and keys', adj.data.shards === 3000 && adj.data.keys === 6, JSON.stringify(adj.data));
s = await shop('buy', { item: 'c_ember' });
ok('buying a rare cape costs 500', s.data.shards === 2500 && s.data.owned.includes('c_ember'));
ok('cannot buy it twice', (await shop('buy', { item: 'c_ember' })).status === 409);
ok('unknown items are refused', (await shop('buy', { item: 'c_free' })).status === 404);
s = await shop('equip', { kind: 'cape', item: 'c_ember' });
ok('equips the cape', s.data.equipped.cape === 'c_ember');
ok('a title cannot go in the cape slot', (await shop('equip', { kind: 'cape', item: 't_wayfarer' })).status === 400);
const notOffered = ['t_wayfarer', 't_stonewright', 't_tinkerer', 'c_mantle', 'c_moss'].find((id) => !s.data.offers.wanderer.includes(id));
ok('cannot pick something the cache is not offering', (await shop('crate', { crate: 'wanderer', item: notOffered, pay: 'shards' })).status === 409);
const pick = s.data.offers.wanderer[1];
const before = s.data.offers.wanderer.join();
s = await shop('crate', { crate: 'wanderer', item: pick, pay: 'keys' });
ok('cache opens with 3 keys and grants the chosen item', s.data.keys === 3 && s.data.owned.includes(pick) && s.data.got === pick, JSON.stringify(s.data).slice(0, 160));
ok('the cache shows a fresh set afterwards', s.data.offers.wanderer.join() !== before && !s.data.offers.wanderer.includes(pick));
const rpick = s.data.offers.reliquary[0];
ok('the reliquary cannot be opened with keys', (await shop('crate', { crate: 'reliquary', item: rpick, pay: 'keys' })).status === 400);
s = await shop('crate', { crate: 'reliquary', item: rpick, pay: 'shards' });
ok('the reliquary opens with 900 shards', s.data.shards === 1600 && s.data.owned.includes(rpick));
const trail = ['tr_dustwake', 'tr_leafdrift'].find((t) => !s.data.owned.includes(t));
await shop('buy', { item: trail });
await shop('buy', { item: 't_tidecaller' });
await shop('equip', { kind: 'trail', item: trail });
s = await shop('equip', { kind: 'title', item: 't_tidecaller' });
ok('title and trail equipped', s.data.equipped.title === 't_tidecaller' && s.data.equipped.trail === trail);

const sign = async (payload) => {
  const t = Math.floor(Date.now() / 1000);
  const key = await crypto.subtle.importKey('raw', new TextEncoder().encode(WH), { name: 'HMAC', hash: 'SHA-256' }, false, ['sign']);
  return `t=${t},v1=${Buffer.from(await crypto.subtle.sign('HMAC', key, new TextEncoder().encode(`${t}.${payload}`))).toString('hex')}`;
};
const unpaid = JSON.stringify({ id: `evt_${tag}`, type: 'checkout.session.completed', data: { object: { id: `cs_${tag}`, mode: 'payment', payment_status: 'unpaid', client_reference_id: me.id, metadata: { kind: 'shards', pid: me.id, shards: '99999' } } } });
const wr = await fetch(base + '/api/stripe/webhook', { method: 'POST', headers: { 'stripe-signature': await sign(unpaid) }, body: unpaid });
s = await shop('state');
ok('an unpaid checkout grants nothing, and metadata is never trusted', wr.status === 200 && s.data.shards === 1600 - 250 - 500);
const forged = await fetch(base + '/api/stripe/webhook', { method: 'POST', headers: { 'stripe-signature': 't=1,v1=00' }, body: unpaid });
ok('a forged webhook is rejected', forged.status === 400);
const co = await shop('checkout', { pack: 0 });
ok('checkout reaches Stripe (fails with the placeholder key)', co.status === 502, JSON.stringify(co.data).slice(0, 120));
ok('checkout refuses an unknown pack', (await shop('checkout', { pack: 7 })).status === 400);

const room = await post('/api/rooms', { name: 'Shard Test', seed: 53, mode: 'creative', difficulty: 'peaceful', ownerId: me.id, ownerSecret: me.secret, ownerName: `shop_${tag}` });
const code = room.data.code;
const c = await new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${code}`);
  const st = { ws, msgs: [] };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); st.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { st.welcome = m; res(st); } };
  ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 43, id: me.id, secret: me.secret, name: `shop_${tag}`, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } }));
});
const mine = (c.welcome?.players ?? []).find((p) => p.id === me.id);
ok('joining a world carries the equipped cosmetics', mine?.cos?.cape === 'c_ember' && mine?.cos?.title === 't_tidecaller', JSON.stringify(mine?.cos ?? c.welcome?.t));
c.ws.send(JSON.stringify({ t: 'chat', text: 'hello shop' }));
await new Promise((r) => setTimeout(r, 500));
const chat = c.msgs.find((m) => m.t === 'chat' && m.text === 'hello shop');
ok('chat carries the title', chat?.from?.cos?.title === 't_tidecaller', JSON.stringify(chat?.from));
c.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
