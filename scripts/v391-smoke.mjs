const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V391', seed: 391, mode: 'survival', difficulty: 'peaceful', ownerId: `own-v391-${tag}`, ownerSecret: 'owner-secret-v391-000', ownerName: 'Alpha' }) })).json();
const join = (id, secret, name) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], closed: null, send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome') { c.you = m.you; c.welcome = m; res(c); } };
  ws.onclose = (e) => { c.closed = e.code; };
  ws.onopen = () => c.send({ t: 'hello', v: 36, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const chats = (c) => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const a = await join(`own-v391-${tag}`, 'owner-secret-v391-000', 'Alpha');
const b = await join(`guest-v391-${tag}`, `guest-secret-v391-${tag}`, 'Bravo');
const seed0 = a.welcome.room.seed;
b.send({ t: 'chat', text: '/sethome base' });
b.send({ t: 'chat', text: '/spawn' });
await sleep(1200);
ok('guests can /sethome', chats(b).some((t) => /Home "base" set/.test(t)), JSON.stringify(chats(b)));
await sleep(1000);
b.send({ t: 'chat', text: '/spawn' });
await sleep(1000);
ok('guests can /spawn', chats(b).some((t) => /world spawn/.test(t)), JSON.stringify(chats(b).slice(-3)));
b.send({ t: 'chat', text: '/countdown 1m Test' });
await sleep(1200);
ok('guests cannot start a countdown', chats(b).some((t) => /permission/.test(t)));
a.send({ t: 'chat', text: '/countdown 90s Boss fight' });
await sleep(1200);
const cd = b.msgs.filter((m) => m.t === 'cd').at(-1);
ok('countdown reaches everyone', cd && cd.l === 'Boss fight' && cd.ms > 80000 && cd.ms <= 90000, JSON.stringify(cd));
a.send({ t: 'chat', text: '/countdown cancel' });
await sleep(1200);
ok('countdown cancel clears it', b.msgs.filter((m) => m.t === 'cd').at(-1)?.ms === 0);
a.send({ t: 'chat', text: '/resetworld 6s' });
await sleep(1200);
ok('refresh needs confirm', chats(a).some((t) => /confirm to schedule/.test(t)));
b.send({ t: 'chat', text: '/resetworld 6s confirm' });
await sleep(1200);
ok('only the owner can refresh', chats(b).some((t) => /Only the world owner/.test(t)));
a.send({ t: 'chat', text: '/resetworld 6s confirm' });
await sleep(9000);
ok('players are told the world refreshed', a.msgs.some((m) => m.t === 'reset') && b.msgs.some((m) => m.t === 'reset'));
ok('sockets were closed', a.closed !== null && b.closed !== null, `${a.closed} ${b.closed}`);
const b2 = await join(`guest-v391-${tag}`, `guest-secret-v391-${tag}`, 'Bravo');
ok('rejoin works and the seed changed', b2.welcome.room.seed !== seed0, `${seed0} -> ${b2.welcome.room.seed}`);
b2.send({ t: 'chat', text: '/homes' });
await sleep(1000);
ok('homes were cleared', chats(b2).some((t) => /no homes/.test(t)), JSON.stringify(chats(b2).slice(-2)));
b2.ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
