const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const r = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'Drafts', seed: 3838, mode: 'creative', difficulty: 'peaceful', ownerId: `owner-v38-${tag}`, ownerSecret: 'owner-secret-v38-0000', ownerName: 'Alpha' }) })).json();
const ws = new WebSocket(`${wsBase}/ws/${r.code}`);
const a = { msgs: [], welcome: null };
ws.onmessage = (e) => { const m = JSON.parse(e.data); a.msgs.push(m); if (m.t === 'welcome') a.welcome = m; };
ws.onopen = () => ws.send(JSON.stringify({ t: 'hello', v: 32, id: `owner-v38-${tag}`, secret: 'owner-secret-v38-0000', name: 'Alpha', appearance: { skin: 1, hair: 2, shirt: 3, pants: 4 } }));
a.send = (m) => ws.send(JSON.stringify(m));
await sleep(1500);
ok('joined', !!a.welcome);
const chats = () => a.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const say = async (t, ms = 700) => { a.send({ t: 'chat', text: t }); await sleep(ms); };
const sp = a.welcome.you;
const x = Math.floor(sp.x) + 4, y = Math.min(150, Math.floor(sp.y) + 30), z = Math.floor(sp.z) + 4;
await say(`/tp ${x} ${y} ${z - 6}`);
a.send({ t: 'mv', p: [x, y, z - 6, 0, 0, 9] }); await sleep(300);
const rle = new Uint16Array([125, 1]);
const enc = `5,5,5|${Buffer.from(rle.buffer).toString('base64')}`;
const upload = async (s, px, py, pz) => {
  const half = Math.ceil(s.length / 2);
  const parts = [s.slice(0, half), s.slice(half)];
  parts.forEach((p, i) => a.send({ t: 'bpc', i, n: parts.length, s: p }));
  a.send({ t: 'bp', x: px, y: py, z: pz, n: parts.length, name: 'Cube' });
};
a.msgs.length = 0;
await upload(enc, x, y, z);
let built = null;
for (let i = 0; i < 30 && !built; i++) { await sleep(400); built = chats().find((t) => /^Built/.test(t)); }
ok('creative player builds a split upload', !!built, JSON.stringify(chats()));
const blk = a.msgs.filter((m) => m.t === 'blk').flatMap((m) => m.u).filter((u) => u[3] === 1);
ok('125 stone blocks broadcast', blk.length === 125, String(blk.length));
a.msgs.length = 0;
await sleep(3200);
await upload(enc, x + 2, y, z);
await sleep(2500);
ok('overlap is refused', chats().some((t) => /overlap|blocked|in the way/i.test(t)) && !chats().some((t) => /^Built/.test(t)), JSON.stringify(chats()));
a.msgs.length = 0;
await say('/gamemode survival', 900);
await sleep(3200);
await upload(enc, x + 10, y, z);
await sleep(2500);
ok('survival without stone is refused', chats().some((t) => /need|missing|materials/i.test(t)) && !chats().some((t) => /^Built/.test(t)), JSON.stringify(chats()));
a.msgs.length = 0;
await say('/gamemode creative', 900);
await say('/gamerule allowBlueprints false', 900);
await sleep(3200);
await upload(enc, x + 20, y, z);
await sleep(1500);
ok('owner toggle disables blueprints', chats().some((t) => /disabled|off|not allowed/i.test(t)) && !chats().some((t) => /^Built/.test(t)), JSON.stringify(chats()));
a.msgs.length = 0;
a.send({ t: 'bpc', i: 0, n: 1, s: '9,9,9|AAAA' });
a.send({ t: 'bp', x, y, z, n: 1, name: 'Bad' });
await sleep(800);
ok('malformed blueprint is rejected', chats().some((t) => /cannot be placed|failed/i.test(t)), JSON.stringify(chats()));
ws.close();
console.log(fails ? `${fails} FAILED` : 'ALL PASSED');
process.exit(fails ? 1 : 0);
