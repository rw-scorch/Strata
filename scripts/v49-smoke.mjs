const base = process.argv[2] ?? 'http://127.0.0.1:8787';
const wsBase = base.replace(/^http/, 'ws');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));
let fails = 0;
const ok = (name, cond, extra = '') => { console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${extra ? ' ' + extra : ''}`); if (!cond) fails++; };
const tag = Date.now().toString(36);
const room = await (await fetch(base + '/api/rooms', { method: 'POST', body: JSON.stringify({ name: 'V49', seed: 49, mode: 'survival', difficulty: 'peaceful', ownerId: `own-v49-${tag}`, ownerSecret: 'owner-secret-v49-0000', ownerName: 'Alpha' }) })).json();
const join = (id, secret, name, v = 40) => new Promise((res) => {
  const ws = new WebSocket(`${wsBase}/ws/${room.code}`);
  const c = { ws, msgs: [], closed: false, send: (m) => ws.send(JSON.stringify(m)) };
  ws.onmessage = (e) => { const m = JSON.parse(e.data); c.msgs.push(m); if (m.t === 'welcome' || m.t === 'err') { c.welcome = m; res(c); } };
  ws.onclose = () => { c.closed = true; res(c); };
  ws.onopen = () => c.send({ t: 'hello', v, id, secret, name, appearance: { skin: 1, hair: 1, shirt: 1, pants: 1 } });
});
const chats = (c) => c.msgs.filter((m) => m.t === 'chat').map((m) => m.text);
const old = await join(`old-v49-${tag}`, `old-secret-v49-${tag}`, 'Oldpage', 39);
ok('protocol 39 page is asked to reload', old.welcome?.t === 'err' && /Reload/.test(old.welcome.msg ?? old.welcome.text ?? JSON.stringify(old.welcome)));
const a = await join(`own-v49-${tag}`, 'owner-secret-v49-0000', 'Alpha');
let g = await join(`guest-v49-${tag}`, `guest-secret-v49-${tag}`, 'Guest');
ok('owner and guest join on protocol 40', a.welcome?.t === 'welcome' && g.welcome?.t === 'welcome');
await sleep(2500);
a.send({ t: 'chat', text: '/ban Guest 2h griefing the spawn' });
await sleep(1200);
ok('owner bans guest for 2 hours', chats(a).some((t) => /Guest/.test(t) && /ban/i.test(t)), chats(a).slice(-1).join(''));
ok('guest is disconnected', g.closed);
g = await join(`guest-v49-${tag}`, `guest-secret-v49-${tag}`, 'Guest');
const why = JSON.stringify(g.welcome);
ok('banned guest sees time left and reason', g.welcome?.t === 'err' && /griefing/.test(why) && /h/.test(why), why.slice(0, 200));
a.send({ t: 'chat', text: '/banlist' });
await sleep(800);
ok('banlist shows the ban', chats(a).slice(-3).some((t) => /Guest/.test(t)), chats(a).slice(-1).join(''));
a.send({ t: 'chat', text: '/ban Alpha perm' });
await sleep(600);
ok('cannot ban yourself', chats(a).slice(-1).some((t) => /yourself|owner/i.test(t)), chats(a).slice(-1).join(''));
a.send({ t: 'chat', text: '/unban Guest' });
await sleep(800);
g = await join(`guest-v49-${tag}`, `guest-secret-v49-${tag}`, 'Guest');
ok('unbanned guest can rejoin', g.welcome?.t === 'welcome');
await sleep(1500);
a.send({ t: 'chat', text: '/ban Guest' });
await sleep(1200);
g = await join(`guest-v49-${tag}`, `guest-secret-v49-${tag}`, 'Guest');
ok('ban without a time is permanent', /permanent/i.test(JSON.stringify(g.welcome)), JSON.stringify(g.welcome).slice(0, 160));
a.send({ t: 'chat', text: '/unban Guest' });
await sleep(600);
a.send({ t: 'chat', text: '/kit preset crystal pvp' });
await sleep(800);
a.send({ t: 'chat', text: '/kit list' });
await sleep(800);
ok('kits save and list in a live world', chats(a).slice(-2).some((t) => /pvp/.test(t)), chats(a).slice(-2).join(' | '));
a.send({ t: 'chat', text: '/rtp' });
await sleep(1500);
ok('rtp responds', chats(a).slice(-2).some((t) => /random|teleport|Landed|warm/i.test(t)), chats(a).slice(-2).join(' | '));
for (const c of [a, g, old]) try { c.ws.close(); } catch {}
console.log(fails ? `${fails} failed` : 'all passed');
process.exit(fails ? 1 : 0);
